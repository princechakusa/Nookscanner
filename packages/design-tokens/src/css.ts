import { breakpoint, color, font, fontSize, motion, radius, shadow, space } from './tokens.ts';

function kebab(key: string): string {
  return key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function flatten(prefix: string, value: unknown, out: Array<[string, string]>): void {
  if (typeof value === 'string' || typeof value === 'number') {
    out.push([prefix, String(value)]);
    return;
  }
  if (value && typeof value === 'object') {
    for (const [k, v] of Object.entries(value)) flatten(`${prefix}-${kebab(k)}`, v, out);
  }
}

/** Generates the CSS custom properties file consumed by all web apps. Deterministic output. */
export function generateCss(): string {
  const vars: Array<[string, string]> = [];
  flatten('--nt-color', color, vars);
  flatten('--nt-font', font, vars);
  for (const [k, [size, line]] of Object.entries(fontSize)) {
    vars.push([`--nt-text-${k}`, size], [`--nt-leading-${k}`, line]);
  }
  space.forEach((v, i) => vars.push([`--nt-space-${i}`, `${v}px`]));
  flatten('--nt-radius', radius, vars);
  flatten('--nt-shadow', shadow, vars);
  flatten('--nt-motion', motion, vars);
  for (const [k, v] of Object.entries(breakpoint)) vars.push([`--nt-breakpoint-${k}`, `${v}px`]);

  const body = vars.map(([k, v]) => `  ${k}: ${v};`).join('\n');
  return `/* GENERATED by packages/design-tokens (npm run generate). Do not edit by hand. */\n:root {\n${body}\n}\n\n:root[dir='rtl'] {\n  --nt-font-latin: var(--nt-font-arabic);\n}\n`;
}
