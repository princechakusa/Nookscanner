CREATE OR REPLACE FUNCTION public.create_invitation(p_org uuid, p_email text, p_role org_role, p_scope member_scope DEFAULT 'organization'::member_scope, p_property_ids uuid[] DEFAULT '{}'::uuid[])
 RETURNS TABLE(invitation_id uuid, token text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_token text := private.generate_token();
  v_id uuid;
begin
  if (select auth.uid()) is null then
    raise exception 'UNAUTHENTICATED' using errcode = '28000';
  end if;
  if not private.has_org_permission(p_org, 'member.manage') then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;
  if p_role = 'owner' then
    raise exception 'OWNER_ROLE_REQUIRED' using errcode = '42501';
  end if;
  if exists (
    select 1 from unnest(coalesce(p_property_ids, '{}')) as pid
    where not exists (select 1 from public.properties p where p.id = pid and p.organization_id = p_org)
  ) then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;
  if exists (
    select 1 from public.organization_members m join auth.users u on u.id = m.user_id
    where m.organization_id = p_org and lower(u.email) = lower(btrim(p_email))
  ) then
    raise exception 'CONFLICT' using errcode = '23505';
  end if;

  insert into public.organization_invitations (organization_id, email, role, scope, property_ids, token_hash, invited_by)
  values (p_org, lower(btrim(p_email)), p_role, p_scope, coalesce(p_property_ids, '{}'),
          encode(sha256(convert_to(v_token, 'UTF8')), 'hex'), (select auth.uid()))
  returning id into v_id;

  return query select v_id, v_token;
end;
$function$;

CREATE OR REPLACE FUNCTION public.create_qr_code(p_apartment uuid, p_label text DEFAULT NULL::text)
 RETURNS qr_codes
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_row public.qr_codes;
begin
  if (select auth.uid()) is null then
    raise exception 'UNAUTHENTICATED' using errcode = '28000';
  end if;
  if not coalesce(private.can_access_apartment(p_apartment, 'qr.manage'), false) then
    raise exception 'NOT_FOUND' using errcode = 'P0002';
  end if;
  insert into public.qr_codes (apartment_id, token, label, created_by)
  values (p_apartment, private.generate_token(), nullif(btrim(p_label), ''), (select auth.uid()))
  returning * into v_row;
  return v_row;
end;
$function$;

CREATE OR REPLACE FUNCTION public.register_media_upload(p_scan_session uuid, p_filename text, p_mime text, p_size_bytes bigint)
 RETURNS media_uploads
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_session public.scan_sessions;
  v_id uuid := gen_random_uuid();
  v_ext text;
  v_row public.media_uploads;
begin
  if (select auth.uid()) is null then
    raise exception 'UNAUTHENTICATED' using errcode = '28000';
  end if;
  -- Lock the session row so concurrent registrations cannot exceed the cap.
  select * into v_session from public.scan_sessions s where s.id = p_scan_session for update;
  if v_session.id is null or not coalesce(private.can_access_apartment(v_session.apartment_id, 'scan.create'), false) then
    raise exception 'NOT_FOUND' using errcode = 'P0002';
  end if;
  if v_session.status not in ('draft', 'recording', 'uploading') then
    raise exception 'CONFLICT' using errcode = '55000';
  end if;
  -- A walkthrough is one or a few files; 20 also covers per-room segments from the app.
  if (select count(*) from public.media_uploads mu where mu.scan_session_id = v_session.id) >= 20 then
    raise exception 'UPLOAD_LIMIT_REACHED' using errcode = '54000';
  end if;

  v_ext := case lower(p_mime) when 'video/mp4' then '.mp4' when 'video/quicktime' then '.mov' end;
  if v_ext is null then
    raise exception 'UPLOAD_REJECTED' using errcode = '22023';
  end if;

  insert into public.media_uploads (id, organization_id, scan_session_id, object_path, original_filename,
                                    mime_type, size_bytes, created_by)
  values (v_id, v_session.organization_id, v_session.id,
          'org/' || v_session.organization_id || '/scans/' || v_session.id || '/' || v_id || v_ext,
          left(btrim(p_filename), 255), lower(p_mime), p_size_bytes, (select auth.uid()))
  returning * into v_row;

  update public.scan_sessions set status = 'uploading' where id = v_session.id and status = 'draft';
  return v_row;
end;
$function$;

CREATE OR REPLACE FUNCTION public.revoke_invitation(p_invitation uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_org uuid;
begin
  select i.organization_id into v_org from public.organization_invitations i where i.id = p_invitation;
  if v_org is null or not private.has_org_permission(v_org, 'member.manage') then
    raise exception 'NOT_FOUND' using errcode = 'P0002';
  end if;
  update public.organization_invitations
  set revoked_at = now()
  where id = p_invitation and accepted_at is null and revoked_at is null;
end;
$function$;

CREATE OR REPLACE FUNCTION public.revoke_qr_code(p_qr uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_apartment uuid;
begin
  select q.apartment_id into v_apartment from public.qr_codes q where q.id = p_qr;
  if v_apartment is null or not coalesce(private.can_access_apartment(v_apartment, 'qr.manage'), false) then
    raise exception 'NOT_FOUND' using errcode = 'P0002';
  end if;
  update public.qr_codes
  set status = 'revoked', revoked_at = now(), revoked_by = (select auth.uid())
  where id = p_qr and status = 'active';
end;
$function$;

CREATE OR REPLACE FUNCTION private.can_access_apartment(p_apartment uuid, p_permission text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select private.can_access_property(a.property_id, p_permission)
  from public.apartments a
  where a.id = p_apartment;
$function$;

CREATE OR REPLACE FUNCTION private.can_access_property(p_property uuid, p_permission text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select coalesce(
    (select private.has_property_permission(pr.organization_id, pr.id, p_permission)
     from public.properties pr where pr.id = p_property),
    false
  );
$function$;

CREATE OR REPLACE FUNCTION private.can_access_scan_session(p_session uuid, p_permission text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select coalesce(
    (select private.can_access_apartment(s.apartment_id, p_permission)
     from public.scan_sessions s where s.id = p_session),
    false
  );
$function$;

CREATE OR REPLACE FUNCTION private.can_access_storage_apartment(p_name text, p_permission text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select coalesce(private.can_access_apartment(private.storage_path_apartment(p_name), p_permission), false);
$function$;

CREATE OR REPLACE FUNCTION private.can_read_raw_footage(p_name text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select exists (
    select 1 from public.media_uploads mu
    where mu.bucket = 'raw-footage'
      and mu.object_path = p_name
      and mu.status <> 'deleted'
      and private.can_access_scan_session(mu.scan_session_id, 'scan.read')
  );
$function$;

CREATE OR REPLACE FUNCTION private.can_upload_raw_footage(p_name text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select exists (
    select 1 from public.media_uploads mu
    where mu.bucket = 'raw-footage'
      and mu.object_path = p_name
      and mu.status = 'pending'
      and mu.created_by = (select auth.uid())
      and private.can_access_scan_session(mu.scan_session_id, 'scan.create')
  );
$function$;
