-- =====================================================================================
-- Nookscanner Stage 2.6 follow-up: hosted Supabase security advisor
-- "authenticated_security_definer_function_executable" (20 WARN on 2026-11-20).
-- Internal SECURITY DEFINER helpers used by RLS policies were callable as REST RPCs
-- (/rest/v1/rpc/...), letting a signed-in user probe facts (e.g. shares_org_with(uuid),
-- storage_path_apartment(text) as an existence oracle). They move to schema `private`, which
-- PostgREST does not expose. Policies keep working (they reference functions by OID); function
-- bodies that call the helpers are rewritten below. Generated by
-- supabase/scripts/gen-private-helpers.mjs from the local stack, then reviewed.
-- The 7 remaining exposed definer functions are the intended RPCs (create_organization,
-- create_invitation, accept_invitation, revoke_invitation, create_qr_code, revoke_qr_code,
-- register_media_upload); each checks auth.uid() and permissions itself (accepted, SECURITY.md 10).
-- =====================================================================================

create schema private;
revoke all on schema private from public;
-- Policies evaluate helpers with the caller's privileges, so authenticated needs usage +
-- execute; the schema is simply not part of the API surface. anon gets nothing.
grant usage on schema private to authenticated, service_role;

alter function public.is_org_member(uuid) set schema private;
